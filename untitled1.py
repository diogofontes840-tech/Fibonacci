n = int(input("Quantas repetições você quer para a sequência de Fibonacci? "))

# Initialize the first two Fibonacci numbers
a, b = 0, 1

# Create a list to store the sequence
fibonacci_sequence = []

# Handle special cases for n=0, n=1, and n=2
if n <= 0:
    print("Por favor, insira um número inteiro positivo.")
elif n == 1:
    fibonacci_sequence.append(a)
else:
    fibonacci_sequence.append(a)
    fibonacci_sequence.append(b)
    # Generate subsequent Fibonacci numbers
    for _ in range(2, n):
        next_fib = a + b
        fibonacci_sequence.append(next_fib)
        a = b
        b = next_fib

print("Sequência de Fibonacci:", fibonacci_sequence)